#include <unistd.h>

void	ft_putnbr(int nb)
{
	char	a;
	char	c;

	c = '-';
	if (nb < 0)
	{
		write(1, &c, 1);
		if (nb / 10)
		{
			ft_putnbr(-(nb / 10));
		}
		a = -(nb % 10) + '0';
	}
	else
	{
		if (nb / 10)
		{
			ft_putnbr(nb / 10);
		}
		a = (nb % 10) + '0';
	}
	write(1, &a, 1);
}
