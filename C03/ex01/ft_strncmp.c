int	ft_strncmp(char *str1, char *str2, unsigned int n)
{
	while ((*str1 || *str2) && n--)
	{
		if (*str1 != *str2)
		{
			return (*str1 - *str2);
		}
		str1++;
		str2++;
		n--;
	}
	return (0);
}
