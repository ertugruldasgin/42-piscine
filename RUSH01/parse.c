#include "rush01.h"

int	parse(char *s, int *clues)
{
	int	i;

	i = 0;
	while (i < 16)
	{
		if (s[i * 2] < '1' || s[i * 2] > '4' || (i < 15 && s[i * 2 + 1] != ' '))
			return (1);
		clues[i] = s[i * 2] - '0';
		i++;
	}
	return (s[31] != '\0');
}
